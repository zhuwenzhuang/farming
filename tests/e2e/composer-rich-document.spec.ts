import { expect, openFarming, test } from './fixtures'

for (const appearance of ['light', 'dark', 'paper']) {
  test(`structured main Chat paste, send, Steer and history in ${appearance}`, async ({ page, workspaceRoot }, testInfo) => {
    test.setTimeout(120_000)
    await page.request.post('/farming/api/settings', { data: { appearance, language: 'en' } })
    const response = await page.request.post('/farming/api/control/agents', { data: { command: 'codex', workspace: workspaceRoot, agentRuntimeMode: 'chat' } })
    const { agentId } = await response.json() as { agentId: string }
    await page.addInitScript(() => Reflect.deleteProperty(Crypto.prototype, 'randomUUID'))
    await openFarming(page)
    expect(await page.evaluate(() => typeof crypto.randomUUID)).toBe('undefined')
    await page.locator(`[data-agent-id="${agentId}"][data-testid="code-agent-row"]`).click()
    const input = page.getByTestId('code-acp-composer-input')
    const source = '# deployment comment\n\techo "<tag> & ```"\n\n# hold for steer without user echo\n'
    await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
    await page.evaluate(async text => {
      const pre = document.createElement('pre');const code = document.createElement('code');code.className = 'language-bash';code.textContent = text;pre.append(code)
      await navigator.clipboard.write([new ClipboardItem({ 'text/plain': new Blob([text], { type: 'text/plain' }), 'text/html': new Blob([pre.outerHTML], { type: 'text/html' }) })])
    }, source)
    await input.focus();await page.keyboard.press('ControlOrMeta+v')
    await expect(input.locator('pre code')).toHaveText(source, { useInnerText: false })
    const editorMod = await page.evaluate(() => /Mac|iP(hone|ad|od)/.test(navigator.platform) ? 'Meta' : 'Control')
    await page.keyboard.press(`${editorMod}+z`);await expect(input).toHaveText('')
    await page.keyboard.press(`${editorMod}+Shift+z`);await expect(input.locator('pre code')).toHaveText(source, { useInnerText: false })
    await page.reload();await expect(input.locator('pre code')).toHaveText(source, { useInnerText: false })
    await page.getByTestId('code-acp-composer-send').click()
    await expect(page.getByText('Waiting for steering.', { exact: true })).toBeVisible()
    const sent = page.getByTestId('code-user-document').first()
    await expect(sent.locator('pre code')).toHaveText(source, { useInnerText: false })
    await expect(sent.locator('h1')).toHaveCount(0)
    const transcript = await (await page.request.get(`/farming/api/agents/${agentId}/acp-transcript`)).text()
    expect(transcript).toContain('farmingInputDocument')
    await input.focus()
    await input.evaluate(element => {
      const data = new DataTransfer();data.setData('text/plain', 'Keep this setting');data.setData('text/html', '<p><strong>Keep this setting</strong></p>')
      element.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
    })
    await expect(input.locator('strong')).toHaveText('Keep this setting')
    await page.getByTestId('code-acp-composer-send').click()
    const steer = page.getByTestId('code-acp-pending-followup-steer')
    if (await steer.count()) await steer.click()
    await expect(page.locator('.code-agent-transcript-answer').last()).toContainText('Steer accepted:')
    await page.reload();await expect(sent.locator('pre code')).toHaveText(source, { useInnerText: false })
    const process = page.getByTestId('code-agent-transcript-process-summary')
    await expect(process).toHaveAttribute('aria-expanded', 'false');await process.click()
    await expect(page.getByTestId('code-agent-transcript-steer').locator('strong')).toHaveText('Keep this setting')
    await input.focus();await page.keyboard.press('ArrowUp')
    await expect(input.locator('strong')).toHaveText('Keep this setting')
    await page.keyboard.press('ArrowUp');await expect(input.locator('pre code')).toHaveText(source, { useInnerText: false })
    await page.setViewportSize({ width: 1280, height: 900 })
    await input.scrollIntoViewIfNeeded()
    const shot = await page.screenshot({ path: testInfo.outputPath(`structured-${appearance}.png`), animations: 'disabled' })
    expect(shot.readUInt32BE(16)).toBe(1280);expect(shot.readUInt32BE(20)).toBe(900)
    await testInfo.attach(`structured-${appearance}`, { body: shot, contentType: 'image/png' })
  })

  test(`structured side Chat keeps independent draft and restores messages in ${appearance}`, async ({ page, workspaceRoot }) => {
    test.setTimeout(120_000)
    await page.clock.install()
    await page.request.post('/farming/api/settings', { data: { appearance, language: 'en' } })
    const response = await page.request.post('/farming/api/control/agents', { data: { command: 'codex', workspace: workspaceRoot, agentRuntimeMode: 'chat' } })
    const { agentId } = await response.json() as { agentId: string }
    await openFarming(page);await page.locator(`[data-agent-id="${agentId}"][data-testid="code-agent-row"]`).click()
    const main = page.locator('.code-composer-shell').getByTestId('code-acp-composer-input')
    await main.fill('/side');await page.locator('.code-composer-shell').getByTestId('code-acp-composer-send').click()
    const panel = page.getByTestId('code-subagent-panel');await expect(panel).toBeVisible()
    await main.fill('Parent draft remains')
    const input = panel.getByTestId('code-acp-composer-input');await input.focus()
    const code = '# side comment\n  echo side'
    await input.evaluate((element, text) => {
      const data = new DataTransfer();data.setData('text/plain', text);data.setData('vscode-editor-data', '{"mode":"shellscript"}')
      element.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
    }, code)
    await expect(input.locator('pre code')).toHaveText(code)
    await panel.getByTestId('code-acp-composer-send').click()
    await expect(panel.getByTestId('code-user-document').locator('pre code')).toHaveText(code)
    await expect(main).toHaveText('Parent draft remains')
    await page.reload();await expect(main).toHaveText('Parent draft remains')
    await page.locator('[data-testid="code-agent-row"].related-child').click()
    await expect(panel).toBeVisible()
    await expect(panel.getByTestId('code-user-document').locator('pre code')).toHaveText(code)

    // Drain incidental setup/reload timers, then freeze the clock so the
    // product-owned 60ms focus retry remains pending while focus moves.
    await page.clock.pauseAt(new Date(Date.now() + 10_000))
    const parentRow = page.locator(`[data-testid="code-agent-row"][data-agent-id="${agentId}"]`)
    await parentRow.evaluate(element => (element as HTMLElement).click())
    await expect(main).toBeFocused()
    await page.locator('[data-testid="code-agent-row"].related-child').evaluate(element => (element as HTMLElement).click())
    await expect(panel).toBeVisible()
    await input.focus()
    await expect(input).toBeFocused()
    const outside = page.getByTestId('code-subagent-panel').getByRole('button', { name: 'Collapse related session' })
    await outside.focus()
    await expect(outside).toBeFocused()
    await page.clock.runFor(61)
    await expect(outside).toBeFocused()
    await input.focus()
    await page.keyboard.press('ArrowUp');await expect(input.locator('pre code')).toHaveText(code)
  })
}
