import type { Locator, TestInfo } from '@playwright/test'
import { expect, openFarming, test } from './fixtures'

async function captureCommunicationStep(surface: Locator, testInfo: TestInfo, name: string) {
  await expect(surface).toBeVisible()
  const image = await surface.screenshot({ path: testInfo.outputPath(name + '.png'), animations: 'disabled' })
  expect(image.readUInt32BE(16)).toBeGreaterThan(300)
  expect(image.readUInt32BE(20)).toBeGreaterThan(150)
}

test('incoming Agent messages use ordinary bubbles and stable attribution in every appearance', async ({ page, workspaceRoot }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.request.post('/farming/api/settings', { data: { language: 'zh' } })
  const created = await page.request.post('/farming/api/control/agents', {
    data: { command: 'codex', workspace: workspaceRoot, agentRuntimeMode: 'chat' },
  })
  expect(created.ok()).toBeTruthy()
  const { agentId } = await created.json() as { agentId: string }
  await openFarming(page)
  await page.locator(`[data-testid="code-agent-row"][data-agent-id="${agentId}"]`).click()
  const input = page.getByTestId('code-acp-composer-input')
  await expect(input).toBeEditable()
  await input.fill('peer incoming appearance')
  await page.getByTestId('code-acp-composer-send').click()
  const sources = page.getByTestId('code-agent-message-source')
  await expect(sources).toHaveCount(2)
  await expect(sources.first()).toHaveText('Cleanroom HDFS TPCDS 单机验收与多机接线')
  await expect(page.getByText('已改名的新任务', { exact: true })).toHaveCount(0)
  await expect(page.getByTestId('code-agent-peer-receipts')).toContainText('1 条 Codex 加密消息')
  await expect(page.locator('.code-agent-transcript-message-unavailable')).toBeHidden()
  const peerBubble = page.locator('.code-agent-transcript-user').filter({ hasText: '我负责 HDFS' })
  await expect(peerBubble).toHaveCount(1)
  const peerMessage = page.locator('.code-agent-transcript-peer-message').filter({ hasText: '我负责 HDFS' })
  await expect(peerMessage.locator('.code-collaboration-agent-icon')).toBeVisible()
  await expect(peerBubble.getByTestId('code-agent-message-source')).toHaveCount(0)
  const continuation = page.locator('.code-agent-transcript-peer-message').filter({ hasText: '补充：两台机器' })
  await expect(continuation.getByTestId('code-agent-message-source')).toHaveCount(0)
  await expect(continuation.locator('.code-collaboration-agent-icon')).toHaveCount(0)
  const laterMessage = page.locator('.code-agent-transcript-peer-message').filter({ hasText: '验收结果会单独' })
  await expect(laterMessage.getByTestId('code-agent-message-source')).toHaveCount(1)
  await expect(page.getByTestId('code-agent-transcript-peer-time')).toHaveCount(3)
  await expect(continuation.getByTestId('code-agent-transcript-peer-time')).toHaveAttribute('datetime', '2026-01-01T10:31:00.000Z')
  await expect(peerMessage.getByTestId('code-agent-transcript-peer-time')).toHaveCount(0)
  for (const appearance of ['light', 'dark', 'paper']) {
    await page.locator('body').evaluate((body, value) => { body.dataset.appearance = value }, appearance)
    await page.evaluate(() => document.fonts.ready)
    await page.mouse.move(1400, 870)
    await expect(peerBubble).toBeVisible()
    expect(await peerBubble.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const sourceStyle = await sources.first().evaluate(element => {
      const style = getComputedStyle(element)
      return { size: style.fontSize, color: style.color, secondary: style.getPropertyValue('--code-text-subtle').trim() }
    })
    const bodyStyle = await peerBubble.evaluate(element => {
      const style = getComputedStyle(element)
      return { size: style.fontSize, color: style.color }
    })
    expect(sourceStyle.size).toBe('12px')
    expect(Number.parseFloat(sourceStyle.size)).toBeLessThan(Number.parseFloat(bodyStyle.size))
    expect(sourceStyle.secondary).not.toBe('')
    expect(sourceStyle.color).not.toBe(bodyStyle.color)
    const bubbleBounds = await peerBubble.boundingBox()
    const nameBounds = await sources.first().boundingBox()
    const avatarBounds = await peerMessage.locator('.code-agent-transcript-peer-avatar').boundingBox()
    expect(nameBounds!.y + nameBounds!.height).toBeLessThanOrEqual(bubbleBounds!.y)
    expect(avatarBounds!.x - (bubbleBounds!.x + bubbleBounds!.width)).toBeCloseTo(10, 0)
    const firstBounds = await peerBubble.boundingBox()
    const nextBounds = await continuation.locator('.code-agent-transcript-user').boundingBox()
    expect(nextBounds!.y - (firstBounds!.y + firstBounds!.height)).toBeCloseTo(4, 0)
    const tailTime = continuation.getByTestId('code-agent-transcript-peer-time')
    expect(await tailTime.evaluate(element => getComputedStyle(element).opacity)).toBe('1')
    expect((await tailTime.boundingBox())!.y).toBeGreaterThanOrEqual(nextBounds!.y + nextBounds!.height)
    const screenshot = await page.getByTestId('code-agent-chat-view').screenshot({ path: testInfo.outputPath(`incoming-${appearance}.png`), animations: 'disabled' })
    expect(screenshot.readUInt32BE(16)).toBeGreaterThan(500)
    expect(screenshot.readUInt32BE(20)).toBeGreaterThan(300)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('body')).toHaveClass(/code-compact-layout/)
  await expect(page.getByTestId('code-mobile-sidebar-backdrop')).toBeHidden()
  await expect.poll(async () => { const bounds = await peerMessage.boundingBox(); return bounds!.x + bounds!.width }).toBeLessThanOrEqual(390)
  for (const appearance of ['light', 'dark', 'paper']) {
    await page.locator('body').evaluate((body, value) => { body.dataset.appearance = value }, appearance)
    await expect(peerMessage).toBeVisible()
    expect(await peerMessage.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const bounds = await peerMessage.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
    const firstBubble = await peerBubble.boundingBox()
    const nextBubble = await continuation.locator('.code-agent-transcript-user').boundingBox()
    expect(nextBubble!.y - (firstBubble!.y + firstBubble!.height)).toBeCloseTo(4, 0)
    expect(await continuation.getByTestId('code-agent-transcript-peer-time').evaluate(element => getComputedStyle(element).opacity)).toBe('1')
    await page.getByTestId('code-agent-chat-view').screenshot({ path: testInfo.outputPath(`incoming-compact-${appearance}.png`), animations: 'disabled' })
  }
  await page.reload()
  await expect(page.getByTestId('code-agent-message-source')).toHaveCount(2)
  await expect(continuation.getByTestId('code-agent-message-source')).toHaveCount(0)
  await expect(page.getByTestId('code-agent-transcript-peer-time')).toHaveCount(3)
  await expect(page.getByTestId('code-agent-message-source').first()).toHaveText('Cleanroom HDFS TPCDS 单机验收与多机接线')
})

test('Farming A2A messages show trusted local sender and navigate across providers', async ({ page, workspaceRoot }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.request.post('/farming/api/settings', { data: { language: 'en' } })
  const create = async (command: string, customTitle: string) => {
    const response = await page.request.post('/farming/api/control/agents', {
      data: { command, customTitle, workspace: workspaceRoot, agentRuntimeMode: 'chat' },
    })
    expect(response.ok()).toBeTruthy()
    return (await response.json() as { agentId: string }).agentId
  }
  const sender = await create('codex', 'API author')
  const recipient = await create('claude', 'Input reviewer')
  await openFarming(page)
  await page.locator(`[data-testid="code-agent-row"][data-agent-id="${sender}"]`).click()
  const input = page.getByTestId('code-acp-composer-input')
  await expect(input).toBeEditable()
  await input.fill(`farming peer send ${recipient}`)
  await page.getByTestId('code-acp-composer-send').click()
  await expect(page.getByTestId('code-agent-chat-view')).toContainText('Sent the review request.')
  await page.locator(`[data-testid="code-agent-row"][data-agent-id="${recipient}"]`).click()
  await expect(page.getByTestId('code-agent-chat-view')).toContainText('The input validation is consistent')
  await expect(page.getByTestId('code-agent-message-source')).toHaveCount(0)
  await page.getByTestId('code-agent-transcript-process-summary').click()
  const peer = page.locator('.code-agent-transcript-peer-message').filter({ hasText: 'Please review the input validation' })
  await expect(peer).toHaveCount(1)
  const source = peer.getByTestId('code-agent-message-source')
  await expect(source).toHaveText('API author')
  await expect(source).toHaveJSProperty('tagName', 'BUTTON')
  await expect(peer.locator('.code-collaboration-agent-icon')).toBeVisible()
  await expect(page.getByTestId('code-agent-chat-view')).toContainText('The input validation is consistent')
  await captureCommunicationStep(page.getByTestId('code-main'), testInfo, 'walkthrough-agent-received')
  await expect(page.getByText('Farming delivered an Agent message', { exact: false })).toHaveCount(0)
  await expect(page.locator('.code-agent-transcript-user').filter({ hasText: 'Please review the input validation' })).toHaveCount(1)
  for (const appearance of ['light', 'dark', 'paper']) {
    await page.locator('body').evaluate((body, value) => { body.dataset.appearance = value }, appearance)
    await page.evaluate(() => document.fonts.ready)
    await page.mouse.move(1400, 870)
    await expect(source).toBeVisible()
    expect(await peer.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const image = await page.getByTestId('code-agent-chat-view').screenshot({ path: testInfo.outputPath(`a2a-${appearance}.png`), animations: 'disabled' })
    expect(image.readUInt32BE(16)).toBeGreaterThan(500)
    expect(image.readUInt32BE(20)).toBeGreaterThan(300)
  }
  const renamed = await page.request.patch(`/farming/api/agents/${sender}`, { data: { customTitle: 'API author renamed' } })
  expect(renamed.ok()).toBeTruthy()
  await expect(source).toHaveText('API author')
  await source.click()
  await expect(page.getByTestId('code-agent-chat-view')).toContainText('Sent the review request.')
  await page.locator(`[data-testid="code-agent-row"][data-agent-id="${recipient}"]`).click()
  await page.reload()
  await expect(page.getByTestId('code-agent-message-source')).toHaveCount(0)
  await page.getByTestId('code-agent-transcript-process-summary').click()
  await expect(peer.getByTestId('code-agent-message-source')).toHaveText('API author')
  await expect(peer.getByTestId('code-agent-message-source')).toHaveJSProperty('tagName', 'BUTTON')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('body')).toHaveClass(/code-compact-layout/)
  for (const appearance of ['light', 'dark', 'paper']) {
    await page.locator('body').evaluate((body, value) => { body.dataset.appearance = value }, appearance)
    await expect(source).toBeVisible()
    const bounds = await peer.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
    expect(await peer.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.getByTestId('code-agent-chat-view').screenshot({ path: testInfo.outputPath(`a2a-compact-${appearance}.png`), animations: 'disabled' })
  }
})


test('receiver inputs without sender metadata stay visible once per message across appearances and reload', async ({ page, workspaceRoot }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const created = await page.request.post('/farming/api/control/agents', {
    data: { command: 'codex', workspace: workspaceRoot, agentRuntimeMode: 'chat' },
  })
  expect(created.ok()).toBeTruthy()
  const { agentId } = await created.json() as { agentId: string }
  await openFarming(page)
  await page.locator(`[data-testid="code-agent-row"][data-agent-id="${agentId}"]`).click()
  await page.getByTestId('code-acp-composer-input').fill('receiver input without sender')
  await page.getByTestId('code-acp-composer-send').click()
  await expect(page.getByText('I received the coordination and continued.', { exact: true })).toBeVisible()
  const receipts = page.getByText('Coordination received while working.', { exact: true })
  await expect(receipts).toHaveCount(0)
  await page.getByTestId('code-agent-transcript-process-summary').click()
  await expect(receipts).toHaveCount(2)
  await expect(page.getByTestId('code-agent-message-source')).toHaveCount(0)
  for (const appearance of ['light', 'dark', 'paper']) {
    await page.locator('body').evaluate((body, value) => { body.dataset.appearance = value }, appearance)
    await expect(receipts.first()).toBeVisible()
    await captureCommunicationStep(page.getByTestId('code-agent-chat-view'), testInfo, `unattributed-${appearance}`)
  }
  await page.reload()
  await expect(receipts).toHaveCount(0)
  await page.getByTestId('code-agent-transcript-process-summary').click()
  await expect(receipts).toHaveCount(2)
})
