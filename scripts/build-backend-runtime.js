#!/usr/bin/env node

'use strict';

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const projectRoot = path.resolve(__dirname, '..');
const backendDir = path.join(projectRoot, 'backend');
const generatedHeader = '// Generated by scripts/build-backend-runtime.js. Do not edit.';

async function main() {
  const entryPoints = fs.readdirSync(backendDir)
    .filter(fileName => fileName.endsWith('.cts'))
    .sort()
    .map(fileName => path.join(backendDir, fileName));
  if (entryPoints.length === 0) {
    throw new Error('No backend TypeScript runtime modules were found');
  }

  for (const fileName of fs.readdirSync(backendDir)) {
    if (!fileName.endsWith('.cjs')) continue;
    const filePath = path.join(backendDir, fileName);
    if (fs.readFileSync(filePath, 'utf8').startsWith(generatedHeader)) fs.rmSync(filePath);
  }

  await esbuild.build({
    entryPoints,
    outdir: backendDir,
    outExtension: { '.js': '.cjs' },
    bundle: false,
    platform: 'node',
    format: 'cjs',
    target: 'node22',
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: generatedHeader },
  });
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
